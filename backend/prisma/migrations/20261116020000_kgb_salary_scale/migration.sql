-- Isi gaji pokok awal dari golongan + MKG berjalan (tahun penuh).
WITH calc AS (
  SELECT e."id", e."golongan",
    LEAST(40, GREATEST(0, DATE_PART('year', AGE(CURRENT_DATE, COALESCE(e."tmt_pangkat_terakhir", e."tanggal_masuk", CURRENT_DATE)))::int)) AS mkg
  FROM "pegawai" e
  WHERE e."golongan" IS NOT NULL
)
UPDATE "pegawai" e
SET "gaji_pokok" = COALESCE(
  (
    SELECT s."gaji_pokok" FROM "skala_gaji_pns" s
    WHERE s."golongan" = e."golongan" AND s."masa_kerja_golongan" <= c.mkg
    ORDER BY s."masa_kerja_golongan" DESC LIMIT 1
  ),
  (
    SELECT s."gaji_pokok" FROM "skala_gaji_pns" s
    WHERE s."golongan" = e."golongan"
    ORDER BY s."masa_kerja_golongan" ASC LIMIT 1
  )
)
FROM calc c
WHERE e."id" = c."id";
